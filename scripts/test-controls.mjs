import assert from 'node:assert/strict';
import {resolve} from 'node:path';
export async function testControls(page,output,checks){
  assert.equal(await page.evaluate(()=>SM64Activity.module._web_rust_adapter_version()),1,'Rust static library is linked and callable');
  await page.locator('#menu-button').click();await page.waitForTimeout(500);
  assert.equal(await page.evaluate(()=>SM64Activity.module._web_ui_state()),1);
  const items=()=>page.evaluate(()=>{const m=SM64Activity.module;m._web_menu_snapshot();return m.webMenuItems;});
  let menu=await items();assert.ok(menu.every(item=>item.x>=0 && item.x+item.width<=1.001),'native menu buttons fit the portrait width');
  await page.screenshot({path:resolve(output,'native-menu.png')});
  const rect=await page.locator('#canvas').boundingBox();
  const point=item=>({x:rect.x+(item.x+item.width/2)*rect.width,y:rect.y+(item.y+item.height/2)*rect.height});
  const options=menu.find(i=>i.label==='Options');assert.ok(options);
  assert.ok(options.height*rect.height>=43,'portrait options have touch-sized targets');
  const p=point(options);await page.mouse.move(p.x,p.y);await page.waitForTimeout(160);
  assert.equal(await page.evaluate(()=>SM64Activity.module._web_hovered()),options.id,'pointer hover selects the original native item');
  await page.mouse.click(p.x,p.y);await page.waitForTimeout(450);menu=await items();
  assert.ok(menu.some(i=>/Camera/.test(i.label)),'click opens native Options');
  await page.screenshot({path:resolve(output,'native-options.png')});
  let back=menu.find(i=>i.label==='Back');assert.ok(back);let b=point(back);
  await page.touchscreen.tap(b.x,b.y);await page.waitForTimeout(350);
  menu=await items();const resume=menu.find(i=>i.label==='Resume');assert.ok(resume,'touch Back returns to native Pause');
  b=point(resume);await page.touchscreen.tap(b.x,b.y);await page.waitForTimeout(300);
  assert.equal(await page.evaluate(()=>SM64Activity.module._web_ui_state()),0,'touch Resume closes native menu');
  checks.push({check:'native pointer hover, click Options, touch Back and Resume',menu});
  if(process.env.SM64_BROWSER==='webkit')return;
  const cdp=await page.context().newCDPSession(page),points=new Map();
  async function touch(type,id,x,y){if(type==='touchEnd'||type==='touchCancel')points.delete(id);else points.set(id,{id,x,y});await cdp.send('Input.dispatchTouchEvent',{type,touchPoints:[...points.values()]});}
  const action=()=>page.evaluate(()=>SM64Activity.module._web_player_action());
  await page.evaluate(()=>{window.__actions=[];window.__recordActions=setInterval(()=>{const a=SM64Activity.module._web_player_action();if(__actions.at(-1)!==a)__actions.push(a);},8);});
  await touch('touchStart',3,300,440);await touch('touchEnd',3);await page.waitForTimeout(100);
  assert.ok(await page.evaluate(()=>__actions.includes(0x00800380)),'tap starts original punching action');
  await page.waitForTimeout(650);
  await touch('touchStart',1,300,440);await touch('touchMove',1,301,370);await touch('touchEnd',1);await page.waitForTimeout(130);
  assert.ok(await page.evaluate(()=>SM64Activity.module._web_airborne()),'up swipe makes the original Mario airborne');
  await touch('touchStart',2,300,440);await touch('touchMove',2,301,510);await touch('touchEnd',2);await page.waitForTimeout(140);
  assert.equal(await action(),0x008008A9,'airborne down swipe starts original ground pound');
  await page.waitForTimeout(1800);
  await touch('touchStart',4,80,610);await touch('touchMove',4,80,550);await page.waitForTimeout(450);
  assert.equal(await action(),0x04000440,'long-jump fixture is running on the ground');
  const z=await page.locator('#touch-crouch').boundingBox(),zx=z.x+z.width/2,zy=z.y+z.height/2;
  await touch('touchStart',5,zx,zy);await touch('touchMove',5,zx,zy-65);await touch('touchEnd',5);await page.waitForTimeout(160);
  assert.equal(await action(),0x03000888,'Z up swipe while moving starts original long jump: '+JSON.stringify(await page.evaluate(()=>__actions)));
  await touch('touchEnd',4);await page.waitForTimeout(900);
  const cameraYaw=()=>page.evaluate(()=>{SM64Activity.module._web_diagnostics();return SM64Activity.diagnostics.camera.yaw;});
  const beforeYaw=await cameraYaw();await touch('touchStart',6,280,440);await touch('touchMove',6,350,445);await touch('touchEnd',6);await page.waitForTimeout(250);assert.notEqual(await cameraYaw(),beforeYaw,'right horizontal drag turns the native camera');
  await page.screenshot({path:resolve(output,'portrait-play.png')});
  checks.push({check:'real touch through Rust into native jump, ground pound, attack and long jump',actions:await page.evaluate(()=>{clearInterval(__recordActions);return __actions;})});
  await page.setViewportSize({width:844,height:390});await page.waitForTimeout(400);await page.screenshot({path:resolve(output,'landscape-play.png')});
  assert.equal(await page.locator('#move-stick').isHidden(),true,'rotation releases the floating stick');
}
